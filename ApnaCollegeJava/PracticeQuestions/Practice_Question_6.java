// Print the numbers from zero to ten. 

public class Practice_Question_6 {
    public static void main(String args[]) {
        // i++ -> i=i+1 (increment operator)
        for(int i=0; i <=10 ; i++) {
            System.out.print(i+" ");
        }

        for(int i=0; i<11; i++) {
            System.out.println(i);
        }
    }
    
}
