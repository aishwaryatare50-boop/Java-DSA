class Variables_and_Datatypes {
    public static void main(String args[]) {
        // variables
        String name  = "Tony Stark";
        System.out.println(name);

        int a = 10;
        int b = 25;

        int sum = a+b;
        System.out.println(sum);

        int diff = b-a;
        System.out.println(diff);

        int mul = a*b;
        System.out.println(mul);

        name = "Ironman";
        System.out.println(name);
    }
}
