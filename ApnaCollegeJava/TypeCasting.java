public class TypeCasting {
    public static void main(String args[]) {
        // casting
        double price = 100.00;
        double finalPrice = price + 18;

        System.out.println(finalPrice);

        int p = 100;
        int fP = p + (int)18.99;
        System.out.println(fP);

        //  Declare Constant 
        final float PI = 3.14F;
        System.out.println(PI);

    }
}
